// Generates the Android launcher icon from the app's figure maths and the
// Forest palette. Pure Dart (no Flutter, no packages); output is deterministic.
//
//   dart run tool/app_icon.dart           write the files (run from the repo root)
//   dart run tool/app_icon.dart --check   fail when a committed file is stale
//
// See docs/modules/app-icon.md.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';

/// Forest `background` and `accent` from `lib/shared/theme/synesterra_theme.dart`
/// (a test keeps them in sync).
const int forestBackground = 0xff111512;
const int forestAccent = 0xffe4b46a;

/// Harmonic amplitudes `s_n` of `z(t) = sum s_n * e^(i * n * t)`; the key is n.
/// The fourth harmonic adds three lobes to the fundamental circle (see
/// `lib/shared/instrument_figure/figure_spec.dart`). 4 * 0.24 < 1, so the
/// curve has pointed lobes and no self-intersections.
const Map<int, double> iconHarmonics = {1: 1.0, 4: 0.24};

/// Adaptive icon canvas and the radius of its guaranteed-visible safe zone, dp.
const double canvasDp = 108;
const double safeRadiusDp = 33;

/// Curve radius and stroke width on the 108 dp canvas. 30 + 4 / 2 = 32 dp stays
/// inside the 33 dp safe radius.
const double figureRadiusDp = 30;
const double strokeDp = 4;

const int _curveSegments = 360;

/// A closed figure curve centred on the origin, farthest point at distance 1,
/// with one lobe pointing up on a screen (y grows downwards).
List<math.Point<double>> figureCurve({int segments = _curveSegments}) {
  final raw = <math.Point<double>>[];
  var farthest = 0.0;
  for (var i = 0; i < segments; i++) {
    final t = 2 * math.pi * i / segments;
    var x = 0.0;
    var y = 0.0;
    iconHarmonics.forEach((n, s) {
      x += s * math.cos(n * t);
      y += s * math.sin(n * t);
    });
    // Rotate by -90 degrees so a lobe points up: (x, y) -> (y, -x).
    final point = math.Point(y, -x);
    raw.add(point);
    farthest = math.max(farthest, point.magnitude);
  }
  return [for (final p in raw) math.Point(p.x / farthest, p.y / farthest)];
}

String _hex(int argb) =>
    '#${(argb & 0xffffff).toRadixString(16).padLeft(6, '0').toUpperCase()}';

/// Vector path data of the curve on the 108 dp canvas.
String figurePathData() {
  final buffer = StringBuffer();
  final curve = figureCurve();
  for (var i = 0; i < curve.length; i++) {
    final x = canvasDp / 2 + curve[i].x * figureRadiusDp;
    final y = canvasDp / 2 + curve[i].y * figureRadiusDp;
    buffer.write(i == 0 ? 'M' : 'L');
    buffer.write('${x.toStringAsFixed(2)},${y.toStringAsFixed(2)}');
  }
  buffer.write('Z');
  return buffer.toString();
}

String _vector(String strokeColor) =>
    '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon.dart. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${canvasDp.toInt()}dp"
    android:height="${canvasDp.toInt()}dp"
    android:viewportWidth="${canvasDp.toInt()}"
    android:viewportHeight="${canvasDp.toInt()}">
    <path
        android:pathData="${figurePathData()}"
        android:strokeColor="$strokeColor"
        android:strokeWidth="${strokeDp.toStringAsFixed(1)}"
        android:strokeLineJoin="round" />
</vector>
''';

/// A non-premultiplied 8-bit RGBA image.
class RgbaImage {
  RgbaImage(this.size, this.pixels);

  final int size;
  final Uint8List pixels;
}

List<int> _rgb(int argb) => [(argb >> 16) & 255, (argb >> 8) & 255, argb & 255];

/// The legacy (pre-adaptive) icon: a rounded square in the background colour
/// with the curve in the accent colour, [size] x [size] pixels. The curve takes
/// the same share of the visible 72 dp area as in the adaptive icon.
RgbaImage renderLegacy(int size) {
  final curve = figureCurve();
  final c = size / 2;
  final radius = size * figureRadiusDp / 72;
  final half = size * strokeDp / 72 / 2;
  final corner = size * 0.2;
  final pixels = Uint8List(size * size * 4);
  final bg = _rgb(forestBackground);
  final fg = _rgb(forestAccent);
  final pts = [
    for (final p in curve) math.Point(c + p.x * radius, c + p.y * radius),
  ];
  final reach = radius + half + 2;

  for (var py = 0; py < size; py++) {
    for (var px = 0; px < size; px++) {
      final x = px + 0.5;
      final y = py + 0.5;
      // Rounded-square coverage from its signed distance.
      final qx = (x - c).abs() - (c - corner);
      final qy = (y - c).abs() - (c - corner);
      final outside = math.sqrt(
        math.pow(math.max(qx, 0), 2) + math.pow(math.max(qy, 0), 2),
      );
      final sd = outside + math.min(math.max(qx, qy), 0) - corner;
      final shape = (0.5 - sd).clamp(0.0, 1.0);

      var stroke = 0.0;
      if (math.sqrt((x - c) * (x - c) + (y - c) * (y - c)) <= reach) {
        var best = double.infinity;
        for (var i = 0; i < pts.length; i++) {
          final a = pts[i];
          final b = pts[(i + 1) % pts.length];
          final dx = b.x - a.x;
          final dy = b.y - a.y;
          final len2 = dx * dx + dy * dy;
          final u = len2 == 0
              ? 0.0
              : (((x - a.x) * dx + (y - a.y) * dy) / len2).clamp(0.0, 1.0);
          final ex = x - (a.x + u * dx);
          final ey = y - (a.y + u * dy);
          best = math.min(best, ex * ex + ey * ey);
        }
        stroke = (half - math.sqrt(best) + 0.5).clamp(0.0, 1.0);
      }

      final o = (py * size + px) * 4;
      for (var k = 0; k < 3; k++) {
        pixels[o + k] = (bg[k] + (fg[k] - bg[k]) * stroke).round();
      }
      pixels[o + 3] = (shape * 255).round();
    }
  }
  return RgbaImage(size, pixels);
}

final _crcTable = () {
  final table = List<int>.filled(256, 0);
  for (var n = 0; n < 256; n++) {
    var c = n;
    for (var k = 0; k < 8; k++) {
      c = (c & 1) != 0 ? 0xedb88320 ^ (c >> 1) : c >> 1;
    }
    table[n] = c;
  }
  return table;
}();

int _crc32(List<int> bytes) {
  var c = 0xffffffff;
  for (final b in bytes) {
    c = _crcTable[(c ^ b) & 255] ^ (c >> 8);
  }
  return c ^ 0xffffffff;
}

List<int> _chunk(String type, List<int> data) {
  final body = [...ascii.encode(type), ...data];
  final length = ByteData(4)..setUint32(0, data.length);
  final crc = ByteData(4)..setUint32(0, _crc32(body));
  return [...length.buffer.asUint8List(), ...body, ...crc.buffer.asUint8List()];
}

/// Encodes [image] as an 8-bit RGBA PNG (filter 0, zlib level 9). The zlib
/// stream may differ between Dart versions, so compare decoded pixels.
List<int> encodePng(RgbaImage image) {
  final n = image.size;
  final raw = BytesBuilder();
  for (var y = 0; y < n; y++) {
    raw.addByte(0);
    raw.add(image.pixels.sublist(y * n * 4, (y + 1) * n * 4));
  }
  final header = ByteData(13)
    ..setUint32(0, n)
    ..setUint32(4, n)
    ..setUint8(8, 8)
    ..setUint8(9, 6);
  return [
    137, 80, 78, 71, 13, 10, 26, 10, //
    ..._chunk('IHDR', header.buffer.asUint8List()),
    ..._chunk('IDAT', ZLibEncoder(level: 9).convert(raw.takeBytes())),
    ..._chunk('IEND', const []),
  ];
}

/// Decodes a PNG written by [encodePng] (RGBA, filter 0 only).
RgbaImage decodePng(List<int> bytes) {
  final data = Uint8List.fromList(bytes);
  final view = ByteData.view(data.buffer);
  var offset = 8;
  var size = 0;
  final idat = BytesBuilder();
  while (offset < data.length) {
    final length = view.getUint32(offset);
    final type = ascii.decode(data.sublist(offset + 4, offset + 8));
    final body = data.sublist(offset + 8, offset + 8 + length);
    if (type == 'IHDR') size = ByteData.view(body.buffer).getUint32(0);
    if (type == 'IDAT') idat.add(body);
    offset += 12 + length;
  }
  final raw = ZLibDecoder().convert(idat.takeBytes());
  final pixels = Uint8List(size * size * 4);
  for (var y = 0; y < size; y++) {
    final from = y * (size * 4 + 1);
    if (raw[from] != 0) {
      throw FormatException('Unsupported PNG filter ${raw[from]}');
    }
    pixels.setRange(y * size * 4, (y + 1) * size * 4, raw, from + 1);
  }
  return RgbaImage(size, pixels);
}

/// Legacy launcher icon sizes in pixels per density folder.
const Map<String, int> legacySizes = {
  'mdpi': 48,
  'hdpi': 72,
  'xhdpi': 96,
  'xxhdpi': 144,
  'xxxhdpi': 192,
};

const String _res = 'android/app/src/main/res';

/// Text files (path relative to the repo root -> content).
Map<String, String> buildTextFiles() => {
  '$_res/values/ic_launcher_background.xml':
      '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon.dart. Do not edit. -->
<resources>
    <color name="ic_launcher_background">${_hex(forestBackground)}</color>
</resources>
''',
  '$_res/drawable/ic_launcher_foreground.xml': _vector(_hex(forestAccent)),
  '$_res/drawable/ic_launcher_monochrome.xml': _vector('#000000'),
  '$_res/mipmap-anydpi-v26/ic_launcher.xml':
      '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon.dart. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''',
};

/// PNG files (path relative to the repo root -> image).
Map<String, RgbaImage> buildImages() => {
  for (final e in legacySizes.entries)
    '$_res/mipmap-${e.key}/ic_launcher.png': renderLegacy(e.value),
  'docs/assets/app-icon-512.png': renderLegacy(512),
  'docs/assets/app-icon-192.png': renderLegacy(192),
};

bool _same(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}

void main(List<String> args) {
  final check = args.contains('--check');
  var stale = 0;

  void emit(String path, List<int> bytes, {required bool decoded}) {
    final file = File(path);
    if (check) {
      var same = file.existsSync();
      if (same) {
        final onDisk = file.readAsBytesSync();
        same = decoded
            ? _same(decodePng(onDisk).pixels, decodePng(bytes).pixels)
            : _same(onDisk, bytes);
      }
      if (!same) {
        stderr.writeln('stale: $path');
        stale++;
      }
      return;
    }
    file.parent.createSync(recursive: true);
    file.writeAsBytesSync(bytes);
    stdout.writeln('wrote $path');
  }

  buildTextFiles().forEach(
    (path, text) => emit(path, utf8.encode(text), decoded: false),
  );
  buildImages().forEach(
    (path, image) => emit(path, encodePng(image), decoded: true),
  );
  if (stale > 0) exit(1);
}
